/*
===============================================================================
Magnitude Analysis
===============================================================================
Purpose:
    - To quantify data and group results by specific dimensions.
    - For understanding data distribution across categories.

SQL Functions Used:
    - Aggregate Functions: SUM(), COUNT(), AVG()
    - GROUP BY, ORDER BY
===============================================================================
*/

-- Find total postings by country
SELECT
    l.country,
    COUNT(*) AS total_postings
FROM gold.fact_postings f
LEFT JOIN gold.dim_locations l
    ON l.location_key = f.location_key
GROUP BY l.country
ORDER BY total_postings DESC;

-- Find total postings by industry
SELECT
    industry,
    COUNT(*) AS total_postings
FROM gold.fact_postings
WHERE industry IS NOT NULL
GROUP BY industry
ORDER BY total_postings DESC;

-- Find total postings by seniority level
SELECT
    seniority_level,
    COUNT(*) AS total_postings
FROM gold.fact_postings
WHERE seniority_level IS NOT NULL
GROUP BY seniority_level
ORDER BY total_postings DESC;

-- What is the average number of benefits listed in each hiring status?
SELECT
    hiring_status,
    AVG(CAST(benefits_count AS FLOAT)) AS avg_benefits
FROM gold.fact_postings
GROUP BY hiring_status
ORDER BY avg_benefits DESC;

-- What is the total number of postings generated by each company?
SELECT
    c.company_key,
    c.company_name,
    COUNT(*) AS total_postings
FROM gold.fact_postings f
LEFT JOIN gold.dim_companies c
    ON c.company_key = f.company_key
GROUP BY
    c.company_key,
    c.company_name
ORDER BY total_postings DESC;

-- What is the distribution of postings across employment types?
SELECT
    employment_type,
    COUNT(*) AS total_postings
FROM gold.fact_postings
WHERE employment_type IS NOT NULL
GROUP BY employment_type
ORDER BY total_postings DESC;
